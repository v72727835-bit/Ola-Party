import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import request from 'supertest';
import { createApp } from '../src/app.js';

test('reference gifts: catalog, 12-seat migration, permissioned invites, custom designs, parcel expiry and idempotent sending', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'party-gifts-')); const file = join(dir, 'state.json');
  let server = createApp({ dataFile: file, demo: true });
  try {
    let api = request(server.app);
    const a = (await api.post('/api/auth/demo').send({})).body.data;
    const b = (await api.post('/api/auth/demo').send({})).body.data;
    const auth = (token: string) => ({ Authorization: 'Bearer ' + token });
    const catalog = (await api.get('/api/gifts/catalog').expect(200)).body.data;
    assert.equal(catalog.categories.length, 10);
    assert.ok(catalog.gifts.length > 180);
    assert.equal(new Set(catalog.gifts.map((g: any) => g.id)).size, catalog.gifts.length);
    for (const category of catalog.categories) assert.ok(catalog.gifts.some((g: any) => g.category === category));
    const room = (await api.post('/api/rooms').set(auth(a.token)).send({ title: 'Reference room' }).expect(200)).body.data;
    assert.equal(room.seats.length, 12);
    await api.post(`/api/rooms/${room.id}/join`).set(auth(b.token)).send({}).expect(200);
    const live = (await api.get(`/api/rooms/${room.id}/live-data`).set(auth(a.token)).expect(200)).body.data;
    assert.equal(live.seats, 12); assert.equal(live.members, 2); assert.equal(live.sentToday, 0);
    await api.post(`/api/rooms/${room.id}/seats/11/invite`).set(auth(b.token)).send({ userId: a.user.id }).expect(403);
    await api.post(`/api/rooms/${room.id}/seats/11/invite`).set(auth(a.token)).send({ userId: b.user.id }).expect(200);
    await api.post(`/api/rooms/${room.id}/seats/11`).set(auth(b.token)).send({ action: 'take' }).expect(200);
    await api.post(`/api/rooms/${room.id}/seats/12`).set(auth(b.token)).send({ action: 'take' }).expect(400);
    const send = (body: any) => api.post('/api/gifts/send').set(auth(a.token)).send({ recipientId: b.user.id, roomId: room.id, ...body });
    await send({ giftId: 'cloudtop-castle', idempotencyKey: 'locked-gift-key' }).expect(403);
    const design = { giftId: 'custom-royal-frame', label: 'My Star', message: 'For you', color: 'pink' };
    await api.post('/api/me/custom-gifts').set(auth(a.token)).send(design).expect(200);
    await api.post('/api/me/custom-gifts').set(auth(a.token)).send({ ...design, giftId: 'rose' }).expect(400);
    const gift = (await send({ giftId: design.giftId, quantity: 5, idempotencyKey: 'custom-send-key' }).expect(200)).body.data.transaction;
    assert.equal(gift.customization.label, design.label); assert.equal(gift.quantity, 5);
    assert.equal((await api.get(`/api/rooms/${room.id}/live-data`).set(auth(a.token))).body.data.sentToday, gift.amount);
    await api.post('/api/me/custom-gifts').set(auth(a.token)).send({ ...design, label: 'Edited design' }).expect(200);
    const history = (await api.get('/api/wallet').set(auth(a.token))).body.data.ledger;
    assert.equal(history.find((t: any) => t.id === gift.id).customization.label, design.label, 'past sends retain their original design');
    await api.post('/api/me/custom-gifts').set(auth(a.token)).send(design).expect(200);
    const walletBefore = (await api.get('/api/wallet').set(auth(a.token))).body.data;
    await send({ giftId: design.giftId, quantity: 5, idempotencyKey: 'custom-send-key' }).expect(200);
    assert.equal((await api.get('/api/wallet').set(auth(a.token))).body.data.coins, walletBefore.coins);
    const parcels = (await api.post('/api/me/gift-inventory/demo').set(auth(a.token)).send({}).expect(200)).body.data;
    const parcel = parcels[0]; assert.equal(parcel.quantity, 5);
    await api.post('/api/me/gift-inventory/demo').set(auth(a.token)).send({}).expect(409);
    await send({ giftId: 'like', idempotencyKey: 'missing-parcel-key' }).expect(409);
    const body = { giftId: 'like', inventoryId: parcel.id, quantity: 2, idempotencyKey: 'parcel-send-key' };
    await send(body).expect(200); await send(body).expect(200);
    assert.equal((await api.get('/api/me/gift-inventory').set(auth(a.token))).body.data[0].quantity, 3);
    assert.equal((await api.get('/api/wallet').set(auth(a.token))).body.data.coins, walletBefore.coins);
    await send({ ...body, quantity: 4, idempotencyKey: 'parcel-too-many' }).expect(409);
    const wall = (await api.get(`/api/users/${b.user.id}/gift-wall`).set(auth(a.token))).body.data;
    assert.equal(wall.gifts.find((g: any) => g.id === 'like').received, 2);
    assert.equal((await api.get('/api/wallet/recharge').set(auth(a.token))).body.data.available, false);
    await server.close();
    const state = JSON.parse(readFileSync(file, 'utf8'));
    state.rooms.find((r: any) => r.id === room.id).seats = room.seats.slice(0, 8);
    state.users.find((u: any) => u.id === a.user.id).giftInventory[0].expiresAt = '2000-01-01T00:00:00.000Z';
    writeFileSync(file, JSON.stringify(state));
    server = createApp({ dataFile: file, demo: true }); api = request(server.app);
    assert.equal((await api.get(`/api/rooms/${room.id}`).set(auth(a.token))).body.data.seats.length, 12);
    assert.equal((await api.get('/api/me/custom-gifts').set(auth(a.token))).body.data[0].label, design.label);
    await send({ ...body, idempotencyKey: 'expired-parcel-key' }).expect(409);
    const real = (await api.post('/api/auth/register').send({ name: 'Real user', email: 'real@test.dev', password: 'password123' })).body.data;
    await api.post('/api/me/gift-inventory/demo').set(auth(real.token)).send({}).expect(403);
  } finally { await server.close(); rmSync(dir, { recursive: true, force: true }); }
});
